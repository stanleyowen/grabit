// Generates Netlify's _redirects and _headers from env at build time.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(root, "public");

const envPath = path.join(root, ".env");
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}

const proxyTarget = (process.env.VITE_API_PROXY_TARGET || "https://yt-dl.stanleyowen.com").replace(/\/$/, "");
const origins = new Set(["'self'"]);
for (const v of [process.env.VITE_API_BASE, process.env.VITE_DOWNLOAD_BASE]) {
  if (v && /^https:\/\//.test(v)) origins.add(new URL(v).origin);
}
const connect = [...origins].join(" ");

fs.mkdirSync(publicDir, { recursive: true });

fs.writeFileSync(
  path.join(publicDir, "_redirects"),
  `# Generated by scripts/generate-netlify.js
/api/*  ${proxyTarget}/api/:splat  200
/*      /index.html                200
`,
);

fs.writeFileSync(
  path.join(publicDir, "_headers"),
  `# Generated by scripts/generate-netlify.js
/*
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: https://i.ytimg.com https://*.ytimg.com https://*.ggpht.com https:; connect-src ${connect}; frame-ancestors 'none'; base-uri 'none'; form-action 'self'; object-src 'none'
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), clipboard-read=(self)

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`,
);

console.log(`Netlify config generated (api proxy -> ${proxyTarget}, connect-src ${connect})`);
